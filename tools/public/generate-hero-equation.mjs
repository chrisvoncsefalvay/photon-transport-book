// Optional asset authoring tool. Normal static builds use the checked-in SVG.
// Requires TeX Live (amsmath, lmodern, standalone) and dvisvgm.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const source = fileURLToPath(
  new URL("../../src/assets/hero/transport-equation.tex", import.meta.url),
);
const target = fileURLToPath(
  new URL("../../src/assets/hero/transport-equation.svg", import.meta.url),
);
const work = mkdtempSync(join(tmpdir(), "dpt-equation-"));
execFileSync(
  "latex",
  [
    "-interaction=nonstopmode",
    "-halt-on-error",
    `-output-directory=${work}`,
    source,
  ],
  { stdio: "pipe" },
);
execFileSync(
  "dvisvgm",
  [
    "--no-fonts",
    "--exact-bbox",
    "--bbox=min",
    `--output=${join(work, "equation.svg")}`,
    join(work, "transport-equation.dvi"),
  ],
  { stdio: "pipe" },
);
const raw = readFileSync(join(work, "equation.svg"), "utf8");
const viewBox = raw.match(/viewBox='([^']+)'/)[1];
const glyphs = new Map(
  [...raw.matchAll(/<path id='([^']+)' d='([^']+)'\/>/g)].map((match) => [
    match[1],
    match[2],
  ]),
);
let index = 0;
const paths = [
  ...raw.matchAll(
    /<use x='([^']+)' y='([^']+)' xlink:href='#([^']+)'\/>|<rect x='([^']+)' y='([^']+)' height='([^']+)' width='([^']+)'\/>/g,
  ),
].map((match) => {
  const delay = (index++ * 0.045).toFixed(3);
  if (match[3]) {
    if (!glyphs.has(match[3])) throw new Error(`Missing glyph ${match[3]}`);
    return `<path class="rte-glyph" pathLength="1" style="--glyph-delay:${delay}s" transform="translate(${match[1]} ${match[2]})" d="${glyphs.get(match[3])}"/>`;
  }
  return `<path class="rte-glyph" pathLength="1" style="--glyph-delay:${delay}s" d="M${match[4]} ${match[5]}h${match[7]}v${match[6]}h-${match[7]}Z"/>`;
});
if (paths.length < 40)
  throw new Error("Unexpected equation output; inspect dvisvgm format.");
writeFileSync(
  target,
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" aria-hidden="true">\n<!-- Generated by generate-hero-equation.mjs; Latin Modern attribution in ATTRIBUTIONS.md. -->\n${paths.join("\n")}\n</svg>\n`,
);
console.log(`Generated ${paths.length} equation outlines.`);
