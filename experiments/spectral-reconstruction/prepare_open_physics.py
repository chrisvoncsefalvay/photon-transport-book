def installed_receipt(name: str, version: str) -> dict[str, Any]:
    distribution = importlib.metadata.distribution(name)
    if distribution.version != version:
        raise ValueError(f"requires {name}=={version}; found {distribution.version}")
    record = distribution.read_text("RECORD")
    if record is None:
        raise ValueError(f"{name} requires a wheel-installed distribution with RECORD")
    files = []
    for relative, identity, size in csv.reader(io.StringIO(record)):
        if not identity:
            continue  # RECORD itself and generated bytecode have no wheel digest.
        algorithm, expected = identity.split("=", 1)
        if algorithm != "sha256":
            raise ValueError(f"unexpected installed wheel digest {algorithm}")
        path = Path(distribution.locate_file(relative))
        actual = digest(path)
        encoded = base64.urlsafe_b64encode(bytes.fromhex(actual)).decode().rstrip("=")
        if encoded != expected or path.stat().st_size != int(size):
            raise ValueError(f"installed {name} differs from its RECORD: {relative}")
        files.append({"file": relative, "bytes": int(size), "sha256": actual})
    return {"name": name, "version": version, "wheel_record_verified_files": files}


def retain_notices(stage: Path) -> list[dict[str, Any]]:
    paths = []
    with tarfile.open(stage / "sources" / PACKAGES[0]["filename"]) as archive:
        for relative in (
            "license_all.txt",
            "license_tom.txt",
            "license_teemu.txt",
            "src/xraylib-nist-compounds-internal.h",
        ):
            member = archive.extractfile("xraylib-4.3.0/" + relative)
            if member is None:
                raise ValueError("missing pinned xraylib notice")
            path = stage / "sources" / ("xraylib-" + Path(relative).name)
            path.write_bytes(member.read())
            paths.append(path)
    with zipfile.ZipFile(stage / "sources" / PACKAGES[1]["filename"]) as archive:
        metadata = archive.read("spekpy-2.5.4.dist-info/METADATA").decode()
        message = email.message_from_string(metadata)
        path = stage / "sources/spekpy-licence.txt"
        path.write_text(str(message["License"]) + "\n")
        paths.append(path)
    return [{"file": str(path.relative_to(stage)), "sha256": digest(path)} for path in paths]


def coefficients(energies: np.ndarray) -> tuple[np.ndarray, list[dict[str, Any]], dict[str, Any]]:
    rows, descriptions, differences = [], [], []
    for identifier, name, density in MATERIALS:
        compound = xraylib.GetCompoundDataNISTByName(name)
        if compound["density"] != density:
            raise ValueError(f"unexpected pinned compound density: {name}")
        fractions = np.asarray(compound["massFractions"])
        # Upstream tabulations have rounded fractions; preserve them exactly.
        np.testing.assert_allclose(fractions.sum(), 1, atol=2e-6, rtol=0)
        total = np.array([xraylib.CS_Total_CP(name, float(e)) for e in energies])
        elemental = np.array(
            [[xraylib.CS_Total(int(z), float(e)) for e in energies] for z in compound["Elements"]]
        )
        mixed = fractions @ elemental
        np.testing.assert_allclose(total, mixed, rtol=3e-14, atol=1e-15)
        differences.append(float(np.max(np.abs(total - mixed))))
        rows.append(total * density / 10.0)
        descriptions.append(
            {
                "id": identifier,
                "reference_name": name,
                "density_g_cm3": density,
                "element_mass_fractions": [
                    {"atomic_number": int(z), "fraction": float(f)}
                    for z, f in zip(compound["Elements"], fractions, strict=True)
                ],
                "element_count": compound["nElements"],
                "composition_interpretation": (
                    "Fixed xraylib reference compound; not patient composition."
                ),
            }
        )
    mu = np.asarray(rows)
    # Independently frozen 80 keV checks distinguish this ICRP model from ICRU-44.
    at80 = [xraylib.CS_Total_CP(name, 80.0) * density / 10 for _, name, density in MATERIALS]
    np.testing.assert_allclose(at80, [0.018365660412653837, 0.04108010415565857], rtol=2e-14)
    return (
        mu,
        descriptions,
        {
            "elemental_mixture_max_absolute_cm2_g": differences,
            "reference_80kev_mm_inv": at80,
            "unit_check": "1 cm path: exp(-kappa*rho) equals exp(-mu_mm_inv*10)",
            "status": "passed",
        },
    )


def sensitivity(mu: np.ndarray, incident: np.ndarray, response: np.ndarray) -> list[dict[str, Any]]:
    checks = []
    for pair in PATHS_MM:
        path = np.asarray(pair, dtype=np.float64)
        photons = response * incident * np.exp(-path @ mu)
        means = photons.sum(axis=1)
        jacobian = -photons @ mu.T
        finite_difference = np.asarray(
            [
                (
                    response @ (incident * np.exp(-(path + 0.001 * axis) @ mu))
                    - response @ (incident * np.exp(-(path - 0.001 * axis) @ mu))
                )
                / 0.002
                for axis in np.eye(2)
            ]
        ).T
        np.testing.assert_allclose(jacobian, finite_difference, rtol=1e-7, atol=1e-10)
        whitened = jacobian / np.sqrt(means[:, None])
        singular = np.linalg.svd(whitened, compute_uv=False)
        rank = int(np.linalg.matrix_rank(whitened))
        if rank != 2 or np.any(means <= 0) or np.any(means >= 2**24):
            raise ValueError("local path rank or expected count range failed")
        checks.append(
            {
                "water_bone_paths_mm": list(pair),
                "expected_counts": means.tolist(),
                "rank": rank,
                "condition_number": float(singular[0] / singular[-1]),
                "singular_values_per_mm": singular.tolist(),
                "poisson_whitened_path_jacobian": whitened.tolist(),
                "finite_difference_step_mm": 0.001,
                "finite_difference": "passed",
            }
        )
    return checks


def prepare(output: Path, caches: list[Path]) -> None:
    installed = [installed_receipt(p["name"], p["version"]) for p in PACKAGES]
    output, stage = external_stage(output)
    write_json(
        stage / "source-license-manifest.json",
        {
            "created_utc": dt.datetime.now(dt.UTC).isoformat(),
            "model_id": MODEL_ID,
            "packages": list(PACKAGES),
            "rights_scope": (
                "Pinned xraylib software, tabulated compounds and total cross sections under "
                "the retained BSD notices; SpekPy package under its MIT notice. No separately "
                "downloaded NIST SRD tables are used or redistributed."
            ),
            "generation_plan": {
                "materials": MATERIALS,
                "spectrum": CONFIGURATION,
                "external_aluminium_filtration": {"thickness_mm": 2.5, "density_g_cm3": 2.699},
                "thresholds_kev": THRESHOLDS,
                "incident_photons": PHOTONS,
            },
        },
    )
    (stage / "sources").mkdir()
    records = [obtain(p, stage / "sources" / p["filename"], caches) for p in PACKAGES]
    notices = retain_notices(stage)
    write_json(stage / "installed-distributions.json", installed)
    spectrum = spekpy.Spek(**CONFIGURATION)
    energies_all, density = spectrum.get_spectrum(edges=False, flu=True, diff=True)
    same, bins = spectrum.get_spectrum(edges=False, flu=True, diff=False)
    np.testing.assert_array_equal(energies_all, same)
    np.testing.assert_array_equal(energies_all, np.arange(1.5, 120.0, 1.0))
    np.testing.assert_allclose(bins, density * CONFIGURATION["dk"], rtol=1e-14)
    wide = spekpy.Spek(**(CONFIGURATION | {"dk": 2.0}))
    _, wide_density = wide.get_spectrum(edges=False, flu=True, diff=True)
    _, wide_bins = wide.get_spectrum(edges=False, flu=True, diff=False)
    np.testing.assert_allclose(wide_bins, 2 * wide_density, rtol=1e-14)
    al_mu = np.array([xraylib.CS_Total(13, float(e)) for e in energies_all]) * 2.699 / 10
    attenuation = np.exp(-2.5 * al_mu)
    filtered_bins = bins * attenuation
    np.savetxt(
        stage / "source-spectrum.csv",
        np.column_stack([energies_all, density, bins, al_mu, attenuation, filtered_bins]),
        delimiter=",",
        header=(
            "energy_kev,unfiltered_density_photons_cm2_kev,unfiltered_bin_photons_cm2,al_mu_mm_inv,al_transmission,filtered_bin_photons_cm2"
        ),
        comments="",
        fmt="%.17g",
    )
    keep = (energies_all >= THRESHOLDS[0]) & (energies_all < THRESHOLDS[-1])
    energies = energies_all[keep]
    incident = filtered_bins[keep] * (PHOTONS / filtered_bins[keep].sum())
    response = np.asarray(
        [(energies >= a) & (energies < b) for a, b in pairwise(THRESHOLDS)],
        dtype=np.float64,
    )
    np.testing.assert_array_equal(response.sum(axis=0), np.ones(100))
    mu, materials, material_checks = coefficients(energies)
    np.savetxt(
        stage / "material-coefficients.csv",
        np.column_stack([energies, mu.T]),
        delimiter=",",
        header="energy_kev,water_mu_mm_inv,icrp_bone_mu_mm_inv",
        comments="",
        fmt="%.17g",
    )
    coefficient_provenance = [
        Provenance(
            source=PACKAGES[0]["download_url"],
            sha256=PACKAGES[0]["sha256"],
            rights=PACKAGES[0]["licence"],
            description=(
                f"xraylib 4.3.0 CS_Total_CP('{m['reference_name']}'); nominal density "
                f"{m['density_g_cm3']} g/cm^3; direct energy evaluation in keV, cm^2/g to mm^-1."
            ),
        )
        for m in materials
    ]
    spectrum_provenance = Provenance(
        source="source-spectrum.csv; https://pypi.org/project/spekpy/2.5.4/",
        sha256=digest(stage / "source-spectrum.csv"),
        rights="Generated spectrum; retain SpekPy MIT and xraylib BSD notices.",
        description=(
            "SpekPy casim W 120 kVp, 12 degrees, PENELOPE attenuation; "
            "explicit xraylib Al 2.5 mm filtration; 200000 photons per "
            "pixel/exposure."
        ),
    )
    supplied = Spectrum(tuple(energies), tuple(incident), "bin-fluence", spectrum_provenance)
    np.testing.assert_array_equal(supplied.bin_fluence, incident)
    acquisition = {
        "generator": "SpekPy",
        "generator_version": "2.5.4",
        "generator_constructor": CONFIGURATION,
        "filtration": [
            {
                "material": "Al",
                "thickness_mm": 2.5,
                "density_g_cm3": 2.699,
                "implementation": "exp(-xraylib.CS_Total(13,E)*density/10*thickness_mm)",
            }
        ],
        "thresholds_kev": list(THRESHOLDS),
        "channel_selection": "Fixed before generation; no optimisation.",
        "response": (
            "Ideal disjoint photon-count channels, unit quantum efficiency, "
            "lower-inclusive upper-exclusive boundaries."
        ),
        "retained_energy_interval_kev": [20, 120],
        "energy_bin_width_kev": 1.0,
        "incident_photons_per_ray_per_exposure_in_retained_interval": PHOTONS,
        "channel_open_beam_expected_counts": (response @ incident).tolist(),
        "excluded_below_20kev_filtered_fluence_fraction": float(
            filtered_bins[~keep].sum() / filtered_bins.sum()
        ),
        "detector_acceptance": (
            "Uniform per-pixel detector-plane fluence; no second area or inverse-square factor."
        ),
        "exposure": 1.0,
        "gain": 1.0,
        "offset": 0.0,
    }
    write_json(stage / "acquisition-definition.json", acquisition)
    response_provenance = Provenance(
        source="acquisition-definition.json",
        sha256=digest(stage / "acquisition-definition.json"),
        rights="Project-authored ideal response model.",
        description=acquisition["response"],
    )
    spec = SpectralSpec(
        materials=2,
        energies=100,
        coefficients_provenance=tuple(coefficient_provenance),
        spectrum_provenance=spectrum_provenance,
        response_provenance=response_provenance,
        output_unit="counts",
        input_description=(
            "Fixed-density xraylib Water, Liquid (1 g/cm^3) and Bone, Cortical (ICRP) "
            "(1.85 g/cm^3) volume fractions; nonnegative sum at most one, remainder vacuum. "
            "Material paths in mm; prescribed ideal detector-plane photon fluence."
        ),
    )
    arrays = {
        "energies_kev": energies,
        "mu_mm_inv": mu,
        "incident_weights": incident,
        "weights": np.broadcast_to(incident, response.shape),
        "response": response,
    }
    arrays = {key: np.ascontiguousarray(value, dtype=np.float32) for key, value in arrays.items()}
    for name, value in arrays.items():
        if not np.isfinite(value).all() or np.any(value < 0):
            raise ValueError(f"invalid export: {name}")
    checks = sensitivity(
        arrays["mu_mm_inv"].astype(np.float64),
        arrays["incident_weights"].astype(np.float64),
        arrays["response"].astype(np.float64),
    )
    np.testing.assert_allclose(arrays["incident_weights"].sum(dtype=np.float64), PHOTONS, rtol=1e-7)
    np.savez(stage / "physics.npz", **arrays)
    metadata = {
        "schema_version": 1,
        "created_utc": dt.datetime.now(dt.UTC).isoformat(),
        "model_id": MODEL_ID,
        "kind": "new_open_simulated_spectral_acquisition",
        "materials": materials,
        "acquisition": acquisition,
        "coefficients_provenance": [dataclasses.asdict(p) for p in coefficient_provenance],
        "spectrum_provenance": dataclasses.asdict(spectrum_provenance),
        "response_provenance": dataclasses.asdict(response_provenance),
        "spectral_spec": dataclasses.asdict(spec),
        "physics_npz_sha256": digest(stage / "physics.npz"),
        "packages": records,
        "notices": notices,
        "unit_conversion": (
            "mu_mm_inv = xraylib total mass attenuation [cm^2/g] * density [g/cm^3] / 10"
        ),
        "interpolation": (
            "Direct xraylib CS_Total_CP evaluation at native spectrum centres;"
            " xraylib handles its tabulated energy interpolation."
        ),
        "energy_integration": (
            "SpekPy diff=False is already integrated per bin; filtration then "
            "retained-bin renormalisation; no second width factor."
        ),
        "arrays": {k: {"shape": list(v.shape), "dtype": str(v.dtype)} for k, v in arrays.items()},
        "validation": {
            "material_checks": material_checks,
            "float32_export_path_checks": checks,
            "nonunit_energy_width": "dk=2: integrated bins equal density times 2",
            "channel_partition": "exactly one channel per retained centre",
        },
        "limitations": [
            (
                "NEW ICRP bone/density and spectrum recipe; does not reproduce the"
                " historical NIST ICRU-44 result."
            ),
            "Anatomical assigned fractions are simulation truth, not measured patient composition.",
            (
                "Generated spectrum and ideal unit-efficiency response; no "
                "measured scanner calibration."
            ),
            (
                "Primary-only attenuation; no scatter, blur, charge sharing, "
                "pileup, read noise or detector response tails."
            ),
            (
                "Sub-20 keV fluence removed and retained interval renormalised; no"
                " heel, bow-tie or detector-plane fluence variation."
            ),
            (
                "Local two-path rank/conditioning is not global tomographic "
                "uniqueness or proof of optimisation convergence."
            ),
        ],
        "environment": {
            "python": platform.python_version(),
            **{n: importlib.metadata.version(n) for n in ("numpy", "scipy", "spekpy", "xraylib")},
        },
        "source_sha256": {
            p.name: digest(p)
            for p in (Path(__file__), Path(__file__).with_name("provision_inputs.py"))
        },
        "source_license_manifest_sha256": digest(stage / "source-license-manifest.json"),
        "installed_distributions_sha256": digest(stage / "installed-distributions.json"),
    }
    for path in (Path(__file__), Path(__file__).with_name("provision_inputs.py")):
        (stage / path.name).write_bytes(path.read_bytes())
    write_json(stage / "metadata.json", metadata)
    stage.rename(output)
    print(
        {
            "output": str(output),
            "model_id": MODEL_ID,
            "physics_npz_sha256": metadata["physics_npz_sha256"],
            "open_beam_counts": acquisition["channel_open_beam_expected_counts"],
            "worst_path_condition": max(r["condition_number"] for r in checks),
        }
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--package-cache", type=Path, action="append", default=[])
    args = parser.parse_args()
    prepare(args.output, args.package_cache)


if __name__ == "__main__":
    main()
