"""Record canonical primary-model recovery from prescribed initial conditions.

The target is an expected image generated by the same discrete model at a known
pose. This isolates software consistency and capture range; it is not measured
data, an anatomical phantom or evidence of robustness to model mismatch.
"""

from __future__ import annotations

import importlib
import json
from dataclasses import asdict
from typing import Any, cast

from dpt.contracts import ContractError, finite_scalar, integer
from dpt.experiments import (
    RunRecorder,
    experiment_parser,
    experiment_sources,
    private_output,
    repository_root,
)
from dpt.geometry import DetectorGeometry, RigidTransform, Vector3
from dpt.objectives import ObjectiveSpec
from dpt.projection import ProjectionSpec, prepare_projection, project_optical_depth
from dpt.recovery import PoseChart, PrimaryPoseEvaluator, PrimaryPoseProblem, recover_pose
from dpt.registration import RecoveryPolicy
from dpt.transmission import TransmissionSpec, prepare_transmission, transmit
from dpt.validation.projection import quadratic_sample_values
from dpt.validation.recovery import pose_error, reprojection_rms_pixels
from dpt.volumes import GridSpec

ROOT = repository_root(__file__)


def main() -> None:
    parser = experiment_parser(__file__, __doc__)
    arguments = parser.parse_args()
    output = private_output(arguments.output, ROOT)
    config = cast(dict[str, object], json.loads(arguments.config.read_text()))
    if (
        set(config)
        != {
            "schema_version",
            "samples_per_ray",
            "open_beam",
            "initial_chart_coordinates",
            "max_iterations",
            "max_evaluations",
            "landmark_success_mm",
            "rotation_success_radians",
        }
        or config["schema_version"] != 1
    ):
        raise ContractError("unsupported pose-recovery configuration")
    samples = integer(config["samples_per_ray"], "samples_per_ray", minimum=1)
    beam = finite_scalar(config["open_beam"], "open_beam", minimum=0)
    if beam == 0:
        raise ContractError("this capture-range experiment requires nonzero illumination")
    raw = config["initial_chart_coordinates"]
    if not isinstance(raw, list) or not raw:
        raise ContractError("declare nonempty initial chart coordinates")
    initials: list[tuple[float, ...]] = []
    for row in cast(list[object], raw):
        if not isinstance(row, list) or len(cast(list[object], row)) != 6:
            raise ContractError("each initial condition needs six chart coordinates")
        initials.append(
            tuple(finite_scalar(x, "initial coordinate") for x in cast(list[object], row))
        )
    policy = RecoveryPolicy(
        max_iterations=integer(config["max_iterations"], "max_iterations", minimum=1),
        max_evaluations=integer(config["max_evaluations"], "max_evaluations", minimum=1),
    )
    landmark_limit = finite_scalar(config["landmark_success_mm"], "landmark limit", minimum=0)
    rotation_limit = finite_scalar(config["rotation_success_radians"], "rotation limit", minimum=0)
    # Snapshot actual package sources, driver, environment lock and exact configuration.
    sources = experiment_sources(__file__, arguments.config)
    with RunRecorder(output, configuration=config, sources=sources) as run:
        wp: Any = importlib.import_module("warp")
        device = wp.get_device(arguments.device)
        if not device.is_cuda:
            raise ContractError("pose recovery requires actual CUDA")
        run.set_metadata(
            device=str(device),
            device_name=device.name,
            architecture=device.arch,
            cuda_driver=device.runtime.driver_version,
            fixture="analytic quadratic field; same-discretisation noiseless expected-image target",
            claim_scope="implementation consistency and prescribed initial conditions",
        )
        grid = GridSpec((20, 22, 24), (0.6, 0.8, 1.0), (-6.7, -8.1, -9.2))
        geometry = DetectorGeometry(
            (-80, 0.37, -0.21), (80, -28, -28), (0, 1, 0), (0, 0, 1), (0.9, 0.9), (64, 64)
        )
        reference = RigidTransform()
        landmarks: tuple[Vector3, ...] = (
            (0, 0, 0),
            (4, 2, 1),
            (-3, 4, -2),
            (2, -3, 5),
            (-4, -2, -3),
        )
        volume = wp.array(
            quadratic_sample_values(grid, intercept=0.01, curvature=(0.0003, 0.0005, 0.0002)),
            dtype=wp.float32,
            device=device,
        )
        pose = wp.array(reference.packed(), dtype=wp.float64, device=device)
        depth = wp.empty(geometry.pixels, dtype=wp.float32, device=device)
        observation = wp.empty(geometry.pixels, dtype=wp.float32, device=device)
        projector = prepare_projection(
            grid, geometry, ProjectionSpec(samples, active_pose=False), device=arguments.device
        )
        transmission = prepare_transmission(
            TransmissionSpec(beam="scalar"), max_pixels=geometry.pixels, device=arguments.device
        )
        project_optical_depth(volume, pose, out_L=depth, workspace=projector)
        transmit(depth, beam, out_counts=observation, workspace=transmission)
        problem = PrimaryPoseProblem(
            grid,
            geometry,
            volume,
            observation,
            ObjectiveSpec(domain="counts", reduction="mean"),
            beam,
            samples_per_ray=samples,
        )
        chart = PoseChart()
        evaluator = PrimaryPoseEvaluator(problem, chart, device=arguments.device)
        records: list[dict[str, object]] = []
        for index, initial in enumerate(initials):
            initial_evaluation = evaluator(initial)
            result = recover_pose(evaluator, initial=initial, policy=policy)
            error = pose_error(result.pose, reference, landmarks)
            record: dict[str, object] = {
                "initial_chart": initial,
                "initial_loss": initial_evaluation.loss,
                "result": asdict(result),
                "pose_error": asdict(error),
                "landmark_reprojection_rms_pixels": reprojection_rms_pixels(
                    result.pose, reference, geometry, landmarks
                ),
                "meets_declared_geometric_criteria": error.landmark_rms_mm <= landmark_limit
                and error.rotation_radians <= rotation_limit,
            }
            run.write_json(f"initial-{index}.json", record)
            records.append(record)
        run.write_json("recovery.json", records)


if __name__ == "__main__":
    main()
